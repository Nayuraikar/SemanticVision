"""Export CVD constants to the viewer (viewer/src/cvd.gen.ts) and reference outputs (tests/fixtures/cvd_expected.json).
`python -m core.perception.export_ts`"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
from . import color as C, cvd
from ._machado_table import MACHADO

TS_OUT = Path("viewer/src/cvd.gen.ts")
FIXTURE = Path("tests/fixtures/cvd_expected.json")
KINDS = ("protan", "deutan", "tritan")
CASES = [("machado", k, s) for k in KINDS for s in (0.0, 0.35, 0.5, 1.0)] + \
        [("vienot", k, s) for k in ("protan", "deutan", "tritan") for s in (0.2, 1.0)] + \
        [("brettel", k, s) for k in KINDS for s in (0.1, 0.3, 1.0)]


def _r(a):
    return np.round(np.asarray(a, float), 9).tolist()


def sample_colors():
    r = np.random.default_rng(7)
    return np.vstack([np.eye(3), np.ones((1, 3)), np.zeros((1, 3)), [[0.8, 0.05, 0.05], [0.1, 0.5, 0.08], [0.9, 0.35, 0.02]],
                      r.uniform(0, 1, (24, 3))])


def ts_source() -> str:
    mach = {k: _r(MACHADO[v]) for k, v in cvd._KIND.items()}
    vien = {k: _r(cvd.vienot_matrix(k)) for k in KINDS}
    bre = {}
    for k in KINDS:
        P1, P2, n, s = cvd.brettel_matrices(k)
        bre[k] = {"p1": _r(P1), "p2": _r(P2), "nsep": _r(n), "sign1": float(s)}
    d = {"machado": mach, "vienot": vien, "brettel": bre, "rgb2lms": _r(C.M_RGB2LMS), "lms2rgb": _r(C.M_LMS2RGB)}
    return "// GENERATED by `python -m core.perception.export_ts`. DO NOT EDIT.\nexport const CVD = " + json.dumps(d) + " as const;\n"


def fixture() -> dict:
    cols = sample_colors()
    cases = [{"model": m, "kind": k, "severity": s, "out": _r(cvd.simulate(cols, m, k, s))} for m, k, s in CASES]
    return {"colors": _r(cols), "cases": cases}


def main():
    TS_OUT.write_text(ts_source())
    FIXTURE.write_text(json.dumps(fixture()))


if __name__ == "__main__":
    main()
