"""Generate TypeScript types from protocol/schemas (single source of truth: protocol/models.py)."""
from __future__ import annotations
import json
from pathlib import Path
from .models import SCHEMA_VERSION
from .schema import export_schemas

HEADER = "// GENERATED by `python -m protocol.ts` from protocol/schemas. DO NOT EDIT.\n"
DEFAULT_OUT = Path("adapters/threejs/protocol.gen.ts")


def _ts(s: dict, ctx: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for k in ("oneOf", "anyOf"):
        if k in s:
            return " | ".join(_ts(x, ctx) for x in s[k])
    t = s.get("type")
    if t == "null":
        return "null"
    if t in ("number", "integer"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts(x, ctx) for x in s["prefixItems"]) + "]"
        return f"Array<{_ts(s.get('items', {}), ctx)}>"
    if t == "object":
        if "properties" in s:
            return _obj(s, ctx)
        ap = s.get("additionalProperties")
        return f"Record<string, {_ts(ap, ctx) if isinstance(ap, dict) and ap else 'unknown'}>"
    return "unknown"


def _obj(s: dict, ctx: dict) -> str:
    req = set(s.get("required", []))
    lines = []
    for k, v in s["properties"].items():
        # fields with defaults are optional on the wire
        opt = "" if k in req else "?"
        lines.append(f"  {json.dumps(k)}{opt}: {_ts(v, ctx)};")
    return "{\n" + "\n".join(lines) + "\n}"


def generate(schema_dir="protocol/schemas") -> str:
    out = [HEADER, f"export const SCHEMA_VERSION = {json.dumps(SCHEMA_VERSION)};\n"]
    seen: set[str] = set()
    for name in ("snapshot", "overrides"):
        s = json.loads((Path(schema_dir) / f"{name}.v{SCHEMA_VERSION}.schema.json").read_text())
        for d, ds in sorted(s.get("$defs", {}).items()):
            if d not in seen:
                seen.add(d)
                out.append(f"export type {d} = {_ts(ds, {})};\n")
        title = s["title"]
        if title not in seen:
            seen.add(title)
            out.append(f"export type {title} = {_ts(s, {})};\n")
    return "\n".join(out)


def write(out=DEFAULT_OUT, schema_dir="protocol/schemas") -> Path:
    export_schemas(schema_dir)
    p = Path(out)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(generate(schema_dir))
    return p


if __name__ == "__main__":
    print(write())
